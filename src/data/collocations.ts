export type PrepositionCategory =
  | 'ABOUT'
  | 'AT'
  | 'BY'
  | 'FOR'
  | 'FROM'
  | 'IN'
  | 'OF'
  | 'ON'
  | 'TO'
  | 'WITH';

export type MasteryStatus = 'unlearned' | 'learning' | 'mastered';

export interface CollocationItem {
  id: string;
  phrase: string;
  adjective: string;
  preposition: PrepositionCategory;
  meaningVi: string;
  example: string;
  structureType?: string; // Especially for TO: "Giới từ (+ V-ing/N)", "Giới từ (+ N)", "To-infinitive (+ V-bare)"
  chunkHighlight: string; // 3-word chunk from section 4.1
  confusingNote?: string;
}

export interface PrepositionMeta {
  key: PrepositionCategory;
  label: string;
  count: number;
  coreIdea: string;
  energyDescription: string;
}

export interface ConfusingPairGroup {
  id: string;
  title: string;
  summary: string;
  items: {
    phrase: string;
    rule: string;
    example: string;
    meaningVi: string;
  }[];
}

