function extractChunkFromExample(phrase: string, preposition: string, example: string): string {
  const prepLower = preposition.toLowerCase();
  const regex = new RegExp(
    `\\b([a-zA-Z]+\\s+${prepLower}\\s+(?:(?:the|a|an|my|your|his|her|our|their|its|this|that|some|any|no)\\s+)?(?:[a-zA-Z'\\-]+\\s+)?[a-zA-Z'\\-]+)`,
    'i'
  );
  const match = example.match(regex);
  if (match && match[1]) {
    return match[1];
  }
  return phrase;
}

